/** 把关卡字面量解析为 boolean[][]（y 行 x 列；结构错误直接抛错，杜绝静默错版） */
export function mazeWalls(maze: MazeId): boolean[][] {
  const layout = MAZE_LAYOUTS[maze];
  if (!layout || layout.length !== ROWS) {
    throw new Error(`snake: 关卡 ${maze} 行数非法（期望 ${ROWS}）`);
  }
  return layout.map((row, y) => {
    if (row.length !== COLS) {
      throw new Error(`snake: 关卡 ${maze} 第 ${y} 行长度非法（期望 ${COLS}）`);
    }
    return [...row].map((ch) => ch === '#');
  });
}

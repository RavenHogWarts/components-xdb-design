/** 7-bag：把七种方块洗匀成一袋（Fisher–Yates，保证每 7 个必出全七种） */
export function shuffledBag(): PieceType[] {
  const bag = [...PIECE_TYPES];
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  return bag;
}

/** Guideline 重力表：各等级每行下落所需帧数（60fps）；29 级以后恒为 1 帧 */
const GRAVITY_FRAMES = [
  48, 43, 38, 33, 28, 23, 18, 13, 8, 6, 5, 5, 5, 4, 4, 4, 3, 3, 3, 2, 2, 2, 2, 2, 2, 2, 2, 2, 2, 1,
];

/** 等级 → 每行下落毫秒数 */
export function gravityMs(level: number): number {
  const frames = GRAVITY_FRAMES[Math.max(0, Math.min(level, GRAVITY_FRAMES.length - 1))];
  return Math.round((frames * 1000) / 60);
}

/** 软降速度：重力的 1/20，下限 16ms（高等级重力快于此时直接用重力速度） */
export function softDropMs(level: number): number {
  return Math.max(16, Math.round(gravityMs(level) / 20));
}
